// Builds the repo-root index.html: one self-contained file (JS + CSS + icons inlined)
// that opens directly from disk with a double-click — no server needed.
import { build } from "esbuild";
import { writeFile } from "node:fs/promises";

const result = await build({
  entryPoints: ["demo/main.tsx"],
  bundle: true,
  minify: true,
  format: "iife",
  jsx: "automatic",
  loader: { ".svg": "dataurl" },
  define: { "process.env.NODE_ENV": '"production"' },
  outdir: "out",
  write: false,
});

const file = (ext) => result.outputFiles.find((f) => f.path.endsWith(ext)).text;
const js = file(".js").replace(/<\/script/gi, "<\\/script");
const css = file(".css");

const html = `<!doctype html>
<html lang="fa">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>Search — suggestion pop-in</title>
<!-- Generated by npm run build:standalone — edit src/, not this file. -->
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Vazirmatn:wght@500&display=swap" rel="stylesheet">
<style>${css}</style>
</head>
<body>
<div id="root"></div>
<script>${js}</script>
</body>
</html>
`;

await writeFile("index.html", html);
console.log(`index.html written (${(html.length / 1024).toFixed(0)} kB)`);
