const FALLBACK = { tag: "سوپرمارکت", body: "کالای اصل با کیفیت تضمین‌شده و ارسال سریع از نزدیک‌ترین فروشگاه.", care: "شرایط نگهداری روی بسته‌بندی درج شده است." };

export function categoryOf(title = "") {
  return CATEGORY.find((c) => c.test.test(title)) || FALLBACK;
}

export function describe(product) {
  const c = categoryOf(product.title);
  const name = [product.title, product.supportingText].filter(Boolean).join(" - ");
  return `${name}\n${c.body}\n${c.care}`;
}
